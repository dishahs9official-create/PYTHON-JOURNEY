'''| **Operator** | **Name**                 | **Description**                          | **Example** | **Output** |
| ------------ | ------------------------ | ---------------------------------------- | ----------- | ---------- |
| `==`         | Equal to                 | Checks if both values are equal          | `5 == 5`    | `True`     |
| `!=`         | Not Equal to             | Checks if values are different           | `5 != 3`    | `True`     |
| `>`          | Greater Than             | Checks if left value is greater          | `5 > 3`     | `True`     |
| `<`          | Less Than                | Checks if left value is smaller          | `5 < 3`     | `False`    |
| `>=`         | Greater Than or Equal To | Checks if left value is greater or equal | `5 >= 5`    | `True`     |
| `<=`         | Less Than or Equal To    | Checks if left value is smaller or equal | `5 <= 3`    | `False`    |
'''
'''Write a python program to show application of relational operator'''

First_num=int(input("Enter first number:"))
Second_num=int(input("Enter second number:"))

a=First_num==Second_num
b=First_num!=Second_num
c=First_num>Second_num
d=First_num>Second_num
e=First_num>=Second_num
f=First_num>=Second_num

print(a)
